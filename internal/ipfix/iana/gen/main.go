// Command gen turns IANA's ipfix-information-elements.csv into a Go table.
//
// It fails on any abstract data type it doesn't know, so a registry update that
// introduces a new type can't slip through silently.
package main

import (
	"bytes"
	"encoding/csv"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"
)

// knownTypes must match iana.DataType; the generated code refers to these constant names.
var knownTypes = map[string]string{
	"unsigned8": "Unsigned8", "unsigned16": "Unsigned16", "unsigned32": "Unsigned32",
	"unsigned64": "Unsigned64", "unsigned256": "Unsigned256",
	"signed8": "Signed8", "signed16": "Signed16", "signed32": "Signed32", "signed64": "Signed64",
	"float32": "Float32", "float64": "Float64", "boolean": "Boolean",
	"macAddress": "MACAddress", "octetArray": "OctetArray", "string": "String",
	"dateTimeSeconds": "DateTimeSeconds", "dateTimeMilliseconds": "DateTimeMilliseconds",
	"dateTimeMicroseconds": "DateTimeMicroseconds", "dateTimeNanoseconds": "DateTimeNanoseconds",
	"ipv4Address": "IPv4Address", "ipv6Address": "IPv6Address",
	"basicList": "BasicList", "subTemplateList": "SubTemplateList", "subTemplateMultiList": "SubTemplateMultiList",
}

// Row is one element parsed from the CSV.
type Row struct {
	ID         uint16
	Name       string
	TypeConst  string
	Semantics  string
	Units      string
	Deprecated bool
}

// Parse reads the registry CSV. Ranges ("105-127") and reserved or unassigned rows are skipped.
func Parse(r io.Reader) ([]Row, error) {
	cr := csv.NewReader(r)
	header, err := cr.Read()
	if err != nil {
		return nil, fmt.Errorf("reading header: %w", err)
	}
	col := map[string]int{}
	for i, h := range header {
		col[h] = i
	}
	for _, need := range []string{"ElementID", "Name", "Abstract Data Type", "Data Type Semantics", "Status", "Units"} {
		if _, ok := col[need]; !ok {
			return nil, fmt.Errorf("CSV has no %q column", need)
		}
	}

	var rows []Row
	for {
		rec, err := cr.Read()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, err
		}
		id, err := strconv.ParseUint(rec[col["ElementID"]], 10, 16)
		if err != nil {
			continue // a range such as "534-32767"
		}
		name := strings.TrimSpace(rec[col["Name"]])
		adt := strings.TrimSpace(rec[col["Abstract Data Type"]])
		if adt == "" || name == "" || strings.EqualFold(name, "Reserved") || strings.EqualFold(name, "Unassigned") {
			continue
		}
		typeConst, ok := knownTypes[adt]
		if !ok {
			return nil, fmt.Errorf("element %d (%s): unknown abstract data type %q; add it to iana.DataType and the generator", id, name, adt)
		}
		rows = append(rows, Row{
			ID:         uint16(id),
			Name:       name,
			TypeConst:  typeConst,
			Semantics:  strings.TrimSpace(rec[col["Data Type Semantics"]]),
			Units:      strings.TrimSpace(rec[col["Units"]]),
			Deprecated: strings.TrimSpace(rec[col["Status"]]) == "deprecated",
		})
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].ID < rows[j].ID })
	return rows, nil
}

// Generate renders rows as gofmt-ed Go source.
func Generate(rows []Row) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by ./gen from ipfix-information-elements.csv. DO NOT EDIT.\n\n")
	b.WriteString("package iana\n\nvar elements = map[uint16]Element{\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t%d: {ID: %d, Name: %q, Type: %s, Semantics: %q, Units: %q, Deprecated: %t},\n",
			r.ID, r.ID, r.Name, r.TypeConst, r.Semantics, r.Units, r.Deprecated)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func main() {
	in := flag.String("in", "ipfix-information-elements.csv", "registry CSV")
	out := flag.String("out", "elements_gen.go", "generated Go file")
	flag.Parse()

	f, err := os.Open(*in)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	rows, err := Parse(f)
	if err != nil {
		log.Fatal(err)
	}
	src, err := Generate(rows)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
